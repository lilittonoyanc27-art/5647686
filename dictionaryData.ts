/**
 * Clean and lookup word in dictionary
 */
export function lookupWord(rawWord: string): WordInfo {
  // Normalize word: remove punctuation, lowercase, strip accents for key search
  const clean = rawWord
    .trim()
    .toLowerCase()
    .replace(/[.,/#!$%^&*;:{}=\-_`~()?"'«»¡¿]/g, '');

  // Exact match
  if (DICTIONARY[clean]) {
    return DICTIONARY[clean];
  }

  // Check without accents
  const deaccent = clean
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');

  if (DICTIONARY[deaccent]) {
    return DICTIONARY[deaccent];
  }

  // Check plural -> singular heuristic
  if (clean.endsWith('es') && DICTIONARY[clean.slice(0, -2)]) {
    return DICTIONARY[clean.slice(0, -2)];
  }
  if (clean.endsWith('s') && DICTIONARY[clean.slice(0, -1)]) {
    return DICTIONARY[clean.slice(0, -1)];
  }

  // Check partial key
  for (const key of Object.keys(DICTIONARY)) {
    if (clean.includes(key) || key.includes(clean)) {
      return DICTIONARY[key];
    }
  }

  // Graceful fallback with phonetic breakdown
  return {
    word: rawWord.trim(),
    translationHy: 'Բառային միավոր (սեղմեք նախադասության վրա ամբողջական թարգմանության համար)',
    pronunciation: `[${rawWord.toLowerCase()}]`,
    partOfSpeech: 'իսպաներեն բառ',
    exampleEs: `En el contexto: "${rawWord}"`,
    exampleHy: `Կոնտեքստում՝ «${rawWord}»`,
  };
}
